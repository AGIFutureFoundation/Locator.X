#!/usr/bin/env python3
"""Generate src/scenes_data.js from content/academy_scenes.json.

The in-app scene cards (src/scenecards.js) read window.LX_SCENES. That object
is a derived file: the scene library has ONE source of truth,
content/academy_scenes.json, and this script is the only thing that writes the
JS. Regenerate, never patch. The library is text — prompt paragraphs — and the
JS carries exactly that text; renders, when they exist, live outside git.

    python3 scripts/gen_scenes_js.py          # validate, then write src/scenes_data.js
    python3 scripts/gen_scenes_js.py --check  # validate, regenerate to a string, exit 1
                                              # if src/scenes_data.js differs (a hand edit,
                                              # or a JSON change nobody regenerated after)

Validation raises - never warns - on: a missing top-level key (version,
reviewed, model, the_line, scenes), a scene missing a required field, a
duplicate scene id, a kind outside the vocabulary scripts/build_scenes.py
enforces (title / exterior / interior / avatar), or a non-title scene with no
`for` (the track, pillar or persona id the scene backs). The content rules —
no real place, one continuous take, the avatar face rule — are
build_scenes.py's job and are not duplicated here.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "content", "academy_scenes.json")
OUT = os.path.join(ROOT, "src", "scenes_data.js")
HEADER = ("/* GENERATED by scripts/gen_scenes_js.py from content/academy_scenes.json "
          "— do not edit */\n")
TOP = ("version", "reviewed", "model", "the_line", "scenes")
REQUIRED = ("id", "title", "pillar", "kind", "initial", "evolution")
# Kept in lockstep with scripts/build_scenes.py KINDS.
KINDS = ("title", "exterior", "interior", "avatar")


def die(msg):
    raise SystemExit("gen_scenes_js: " + msg)


def load():
    with open(SRC, encoding="utf-8") as fh:
        return json.load(fh)


def validate(data):
    for key in TOP:
        if key not in data:
            die("top-level key %r missing" % key)
    if not isinstance(data["scenes"], list) or not data["scenes"]:
        die("scenes is empty")
    if not str(data["the_line"]).strip():
        die("the_line is empty - the boundary sentence is what the cards print")
    seen = set()
    for sc in data["scenes"]:
        sid = sc.get("id", "<no id>")
        missing = [k for k in REQUIRED if k not in sc]
        if missing:
            die("scene %r missing %s" % (sid, ", ".join(missing)))
        if not re.fullmatch(r"[a-z][a-z0-9-]*", sid):
            die("scene id %r is not kebab-case" % sid)
        if sid in seen:
            die("duplicate scene id %r" % sid)
        seen.add(sid)
        if sc["kind"] not in KINDS:
            die("scene %r: kind %r is not one of %s" % (sid, sc["kind"], ", ".join(KINDS)))
        if sc["kind"] != "title" and not sc.get("for"):
            die("scene %r: a %s scene must say what it backs (`for`: a track, pillar "
                "or persona id)" % (sid, sc["kind"]))
        for field in ("initial", "evolution"):
            if not str(sc[field]).strip():
                die("scene %r: %s is empty" % (sid, field))
    return len(seen)


def render(data):
    out = {k: data[k] for k in TOP}
    body = json.dumps(out, ensure_ascii=False, separators=(",", ":"), sort_keys=False)
    return HEADER + "window.LX_SCENES = " + body + ";\n"


def main(argv):
    data = load()
    n = validate(data)
    js = render(data)
    rel = os.path.relpath(OUT, ROOT)
    if "--check" in argv:
        if not os.path.exists(OUT):
            print("gen_scenes_js --check: %s does not exist; run without --check" % rel)
            return 1
        with open(OUT, encoding="utf-8") as fh:
            current = fh.read()
        if current != js:
            print("gen_scenes_js --check: %s is not what content/academy_scenes.json "
                  "generates - it has been hand-edited, or academy_scenes.json changed and "
                  "nobody regenerated. Run python3 scripts/gen_scenes_js.py" % rel)
            return 1
        print("gen_scenes_js --check: src/scenes_data.js matches content/academy_scenes.json "
              "(%d scenes)" % n)
        return 0
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(js)
    print("wrote %s (%d scenes)" % (rel, n))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
